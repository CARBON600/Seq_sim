"""Command-line entry point and simulation pipeline for seq_sim.

Parses CLI options, initialises the substitution-model registry (or GFmix
profile mixture models), reads Newick or NEXUS trees, and runs the sequence
evolution loop across partitions and replicates.
"""

import argparse
import locale
import os
import re
import sys
import time
from collections import namedtuple

import numpy as np

from ._version import __version__
from .core.aa_models import empirical_rates
from .core.evolve import _raise_recursion_limit, evolve_sequences
from .core.models import AA_MODELS, build_model_registry, setup_model
from .core.profile_mixture import assign_site_profiles, build_profile_models, normalise_weights
from .core.rate_heterogeneity import assign_categories, normalise_branch_rates, setup_rates
from .io.nexus_reader import is_nexus, parse_nexus_tree_entries
from .io.writers import write_ancestral_multi, write_rates, write_sequences
from .manual import get_manual
