"""Empirical amino-acid substitution models: JTT, WAG, PAM, BLOSUM62, LG, GENERAL.
Twenty-state time-reversible models in ARNDCQEGHILKMFPSTWYV order. Each model
holds 190 upper-triangle exchangeabilities and 20 equilibrium frequencies,
transcribed from Seq-Gen 1.3.5 source/aamodels.c (DCMUT-corrected JTT and PAM).
Q = R diag(pi) is scaled to mean rate 1 and symmetrised as S = sqrt(pi) Q / sqrt(pi)
before one eigendecomposition.
input: model name, exchangeabilities, equilibrium frequencies
output: a model object with set_matrix / set_vector and a cached spectrum
"""

import numpy as np

from ._validators import (check_relative_rates, normalise_freqs, validate_aa_freqs,
                          validate_length, validate_state)

NUM_AA = 20
NUM_AA_REL_RATES = 190
AA_CHARS = "ARNDCQEGHILKMFPSTWYV"
AA_ORDER = list(AA_CHARS)


class AAModel:
    """Amino-acid model, 20x20 symmetric eigendecomposition of Q.

    Built like GTRModel: Q = R * diag(pi) scaled to mean rate 1, then
    S = sqrt(pi) Q / sqrt(pi) is decomposed once, so any branch length is a
    spectral update rather than a fresh matrix exponential.
    """

    def __init__(self, freqs, relative_rates):
        if len(freqs) != NUM_AA:
            raise ValueError(f"freqs must contain exactly {NUM_AA} amino acid "
                             f"frequencies, got {len(freqs)}")
        validate_aa_freqs(freqs, AA_ORDER)
        check_relative_rates(relative_rates, NUM_AA_REL_RATES)

        self.num_states = NUM_AA
        self.state_chars = AA_CHARS
        pi = np.array(freqs, dtype=np.float64)
        self.freq = pi
        self.cum_freqs = np.cumsum(pi)

        R = np.zeros((NUM_AA, NUM_AA))
        k = 0
        for i in range(NUM_AA - 1):
            for j in range(i + 1, NUM_AA):
                R[i][j] = R[j][i] = relative_rates[k]
                k += 1

        Q = R * pi[None, :]
        mean_rate = 0.0
        for i in range(NUM_AA):
            row_sum = np.sum(Q[i])
            Q[i][i] = -row_sum
            mean_rate += pi[i] * row_sum
        if not np.isfinite(mean_rate) or mean_rate <= 0.0:
            raise ValueError("invalid mean substitution rate: " + repr(mean_rate))
        Q /= mean_rate

        sqrt_pi = np.sqrt(pi)
        S = sqrt_pi[:, None] * Q * (1.0 / sqrt_pi)[None, :]
        asym = np.max(np.abs(S - S.T))
        if asym > 1e-12:
            raise FloatingPointError(
                f"AA reversible transform is unexpectedly asymmetric: {asym}")
        S = 0.5 * (S + S.T)

        self._roots, self._eigvecs = np.linalg.eigh(S)
        self._sqrt_pi = sqrt_pi

    def set_matrix(self, matrix, length):
        length = validate_length(length)
        m = matrix.reshape(self.num_states, self.num_states)
        if length == 0.0:
            m[:] = np.eye(self.num_states)
        else:
            E = self._eigvecs * np.exp(self._roots * length)[None, :]
            E = E @ self._eigvecs.T
            m[:] = E * (self._sqrt_pi[None, :] / self._sqrt_pi[:, None])
        min_prob = np.min(m)
        if min_prob < -1e-12:
            raise FloatingPointError(
                f"AA transition matrix contains significantly negative "
                f"probability: {min_prob}")
        m[m < 0.0] = 0.0
        m /= m.sum(axis=1, keepdims=True)
        np.cumsum(m, axis=1, out=m)
        m[:, -1] = 1.0

    def set_vector(self, vector, state, length):
        state = validate_state(state, self.num_states)
        length = validate_length(length)
        v = vector[:self.num_states]
        if length == 0.0:
            v[:] = 0.0
            v[state] = 1.0
        else:
            E_row = self._eigvecs[state] * np.exp(self._roots * length)
            v[:] = E_row @ self._eigvecs.T
            v[:] *= self._sqrt_pi / self._sqrt_pi[state]
        min_prob = np.min(v)
        if min_prob < -1e-12:
            raise FloatingPointError(
                f"AA transition vector contains significantly negative "
                f"probability: {min_prob}")
        v[v < 0.0] = 0.0
        total = v.sum()
        if total > 0.0:
            v /= total
        np.cumsum(v, out=v)
        v[-1] = 1.0


def create_aa_model(name, user_freqs=None, user_rates=None, equal_freqs=False):
    """Build an AAModel; user values override the built-in ones."""
    name = name.upper()
    emp = _EMPIRICAL_MODELS.get(name)
    if emp is None and name != "GENERAL":
        raise ValueError(f"Unknown AA model: {name}")

    if name == "GENERAL":
        if user_rates is None:
            raise ValueError("GENERAL model requires user-supplied relative_rates")
        if user_freqs is None:
            raise ValueError("GENERAL model requires user-supplied freqs")
        rates = list(user_rates)
        freqs = list(user_freqs)
    else:
        rates = list(user_rates) if user_rates is not None else list(emp["rates"])
        if user_freqs is not None:
            freqs = list(user_freqs)
        elif equal_freqs:
            freqs = [1.0 / NUM_AA] * NUM_AA
        else:
            freqs = list(emp["freqs"])

    normalise_freqs(freqs)
    return AAModel(freqs, rates)


def empirical_rates(name):
    """Return the 190 exchangeabilities of a built-in empirical model."""
    emp = _EMPIRICAL_MODELS.get(name.upper())
    if emp is None:
        raise ValueError(f"unknown AA model: {name}")
    return list(emp["rates"])


