"""Command-line entry point and simulation pipeline.

Usage: python -m seq_sim_v2 -m HKY -l 1000 tree.nwk

Model       : orchestration only. The command line is validated, the model
              registry is built, the tree is read, and the evolution loop is run
              once per replicate.
Equation    : the GFmix branch transform is applied here, through
              _apply_branch_gammas, to the node objects before evolution starts;
              the transform itself lives in core/profile_mixture.py.
Source      : the CLI conventions follow Seq-Gen (_m, -l, -a, -g and so on);
              the GFmix options are this project's own. See docs/REFERENCES.md.
Convention  : model index 0 in the registry is always the model built from the
              command line; --alt-freqs, --alt-rates and --alt-tstv add indices
              from 1. --gfmix-cseries is mutually exclusive with the --alt-*
              options. The manual in manual.py is part of the interface: a new
              option is not complete until --manual documents it.
Invariants  : a fixed -z with a fixed tree reproduces a run byte for byte; the
              hashes in tests/test_golden.py fail if the order or arithmetic of
              the draws changes.
"""

import argparse
import locale
import os
import re
import sys
import time
from collections import namedtuple

import numpy as np

from ._version import __version__
from .utils import create_seed, random, set_seed
from .core.models import AA_MODELS, build_model_registry, setup_model
from .core.aa_models import empirical_rates
from .core.cseries import load_cseries
from .core.profile_mixture import assign_site_profiles, build_profile_models
from .core.rate_heterogeneity import (
    assign_categories, normalize_branch_rates, setup_rates)
from .core.evolve import _raise_recursion_limit, evolve_sequences
from .tree.tree_parser import allocate_sequences, dispose_tree, parse_trees
from .output.writers import write_ancestral, write_rates, write_sequences
from .output.nexus_reader import is_nexus, parse_nexus_trees
from .manual import get_manual

NEXUS_HEADER = "#NEXUS\n[\nGenerated by seq_sim\n]\n\n"

# Values fixed for the whole run, bundled so _write_dataset stays readable.
_Run = namedtuple("_Run", "fmt state_chars is_nuc rate_info insert_text "
                          "multi_tree multi_dataset")


def _warn(message):
    sys.stderr.write(f"Warning: {message}\n")


def _die(message):
    sys.exit(f"Error: {message}")


def _read_text(path):
    """Read a text file as UTF-8, falling back to the locale encoding."""
    try:
        with open(path, encoding="utf-8-sig") as f:
            return f.read()
    except UnicodeDecodeError:
        enc = locale.getpreferredencoding(False)
        _warn(f"'{path}' is not valid UTF-8; decoding as {enc}.")
        with open(path, encoding=enc, errors="replace") as f:
            return f.read()


def main():
    args = _parse_args()

    if args.seed is not None:
        seed = args.seed
    else:
        seed = create_seed()
    set_seed(seed)

    if not args.quiet:
        sys.stderr.write(f"seq_sim v{__version__}\n  Random seed: {seed}\n\n")

    if args.treefile:
        tree_text = _read_text(args.treefile)
    else:
        if hasattr(sys.stdin, "reconfigure"):
            sys.stdin.reconfigure(encoding="utf-8", errors="replace")
        tree_text = sys.stdin.read()
    if not tree_text.strip():
        _die("no tree data provided")

    rooted_flags = []
    translate_map = None
    if is_nexus(tree_text):
        translate_map, nexus_trees = parse_nexus_trees(tree_text)
        tree_text = "\n".join(t for t, _ in nexus_trees)
        rooted_flags = [r for _, r in nexus_trees]
        if not args.quiet and (args.alt_freqs_list or args.alt_rates_list
                               or args.alt_tstv):
            _warn("NEXUS input — only [f=N]/[r=N] branch annotations are "
                  "preserved; other [...] comments are stripped.")

    model = setup_model(
        args.model,
        tstv=args.tstv,
        equal_exchangeability=(args.tstv is None),
        freqs=args.freqs,
        equal_freqs=args.equal_freqs,
        relative_rates=args.rates,
    )
    state_chars = model.state_chars
    is_nuc = model.num_states == 4

    model_registry = build_model_registry(
        args.model,
        freqs=args.freqs,
        tstv=args.tstv,
        equal_exchangeability=(args.tstv is None),
        equal_freqs=args.equal_freqs,
        relative_rates=args.rates,
        alt_freqs=args.alt_freqs_list,
        alt_tstv=args.alt_tstv,
        alt_rates=args.alt_rates_list,
    )

    rate_info = setup_rates(
        args.total_sites,
        codon_rates=args.codon_rates,
        gamma_shape=args.gamma,
        gamma_cats=args.gamma_cats,
        invariable=args.invariable,
        write_rates=args.write_rates,
    )

    raw_trees = parse_trees(tree_text, translate_map)
    if rooted_flags:
        for (_, _, tree), rooted in zip(raw_trees, rooted_flags):
            if rooted is not None:
                tree.rooted = rooted

    datasets = _group_partitions(raw_trees, args.total_sites)
    max_nodes = max((tree.num_nodes for parts in datasets
                     for _, _, tree in parts), default=0)
    _raise_recursion_limit(max_nodes)

    # GFmix site-and-branch heterogeneity (amino-acid models only).
    profile_info = None
    gamma_by_name = {}
    if args.gfmix_cseries is not None:
        gamma_by_name = (_parse_branch_hetero(args.gfmix_branch_hetero)
                         if args.gfmix_branch_hetero else {})
        _apply_branch_gammas(datasets, gamma_by_name)
        gamma_by_node = {}
        for parts in datasets:
            for _, _, tree in parts:
                for node in tree.node_list:
                    if node.gamma_g != 1.0 or node.gamma_f != 1.0:
                        gamma_by_node[node] = (node.gamma_g, node.gamma_f)
        model_name = "GTR" if args.model.upper() == "REV" else args.model.upper()
        exchangeability = _exchangeability_for(model_name, args.rates)
        base_models, per_node, c_weights = build_profile_models(
            args.gfmix_cseries, exchangeability, gamma_by_node)
        c_count = len(c_weights)
        if args.gfmix_weights is not None:
            if len(args.gfmix_weights) != c_count:
                _die(f"--gfmix-weights expects {c_count} values for "
                     f"{args.gfmix_cseries}, got {len(args.gfmix_weights)}")
            weights = np.array(args.gfmix_weights, dtype=np.float64)
            if abs(float(weights.sum()) - 1.0) > 1e-9:
                _die("--gfmix-weights must sum to 1")
        else:
            weights = c_weights
        profile_info = {
            "cseries": args.gfmix_cseries,
            "num_profiles": c_count,
            "weights": weights,
            "site_profile": np.zeros(args.total_sites, dtype=np.int64),
            "base_models": base_models,
            "per_node": per_node,
        }

    # Reject bad scaling and ancestor input before any output directory exists.
    if args.tree_scale > 0:
        for parts in datasets:
            for _, _, tree in parts:
                if not tree.rooted:
                    _die("-d/--tree-scale requires a rooted tree. "
                         "Use -s/--branch-scale for unrooted trees.")
                if tree.total_length <= 0.0:
                    _die("-d/--tree-scale requires a tree with a positive "
                         "root-to-tip height.")
    if args.ancestor is not None:
        if len(args.ancestor) != args.total_sites:
            _die(f"--ancestor length {len(args.ancestor)} does not match "
                 f"-l/--length {args.total_sites}.")
        bad = sorted({c.upper() for c in args.ancestor} - set(state_chars))
        if bad:
            _die(f"--ancestor contains invalid state(s) for model "
                 f"{args.model}: {''.join(bad)}")

    fmt = args.format
    separate = args.separate or (fmt == "f")
    out_prefix = args.output_prefix or "output"
    out_base = os.path.basename(out_prefix) or out_prefix
    suffix = args.suffix or _default_suffix(fmt)
    os.makedirs(out_prefix, exist_ok=True)

    run = _Run(fmt=fmt,
               state_chars=state_chars,
               is_nuc=is_nuc,
               rate_info=rate_info,
               insert_text=_read_text(args.insert_file) if args.insert_file else None,
               multi_tree=len(datasets) > 1,
               multi_dataset=args.num_datasets > 1)

    gfmix_log_fv = None
    if profile_info is not None and args.gfmix_log:
        gfmix_log_fv = open(os.path.join(out_prefix, out_base + ".gfmix.log"),
                            "w", encoding="utf-8", newline="\n")
        _write_gfmix_log_header(gfmix_log_fv, profile_info, gamma_by_name)

    if args.branch_rates:
        if args.normalize_branch_rates:
            normalize_branch_rates(datasets)
    else:
        for parts in datasets:
            for _, _, tree in parts:
                for node in tree.node_list:
                    node.param = 1.0

    started = time.time()
    for ds_idx, parts in enumerate(datasets):
        tree_no = ds_idx + 1

        for part_len, _, tree in parts:
            allocate_sequences(tree, part_len)
        _rescale_partitions(parts, args.total_sites)

        if ds_idx == 0 and not args.quiet:
            _print_model_info(args, model, rate_info, fmt, out_prefix)

        for rep in range(args.num_datasets):
            dataset_no = rep + 1
            assign_categories(rate_info, args.total_sites, args.gamma,
                              args.gamma_cats)
            if profile_info is not None:
                profile_info["site_profile"][:] = assign_site_profiles(
                    args.total_sites, profile_info["weights"], random)

            offset = 0
            for part_len, part_rate, tree in parts:
                scale = _branch_scale(args, part_rate, tree)
                if not args.quiet and ds_idx == 0 and rep == 0:
                    _report_height(args, tree, scale)
                evolve_sequences(tree, offset, part_len, scale,
                                 model_registry, rate_info, args.ancestor,
                                 profile_info)
                offset += part_len
            if gfmix_log_fv is not None:
                _write_gfmix_log_replicate(gfmix_log_fv, dataset_no,
                                           profile_info["site_profile"])

            if run.multi_dataset:
                file_no, n_files = rep + 1, args.num_datasets
            else:
                file_no, n_files = tree_no, len(datasets)

            if separate:
                padding = max(1, len(str(n_files)))
                name = f"{out_base}_{file_no:0{padding}d}.{suffix}"
                mode = "w"
            else:
                name = f"{out_base}.{suffix}"
                mode = "w" if (ds_idx == 0 and rep == 0) else "a"

            with open(os.path.join(out_prefix, name), mode,
                      encoding="utf-8", newline="\n") as fv:
                if fmt == "n" and mode == "w":
                    fv.write(NEXUS_HEADER)
                _write_dataset(fv, args, run, [t for _, _, t in parts],
                               [pl for pl, _, _ in parts], tree_no, dataset_no)

        for _, _, tree in parts:
            dispose_tree(tree)

    if gfmix_log_fv is not None:
        gfmix_log_fv.close()

    if not args.quiet:
        sys.stderr.write(f"Time taken: {time.time() - started:.3f} seconds\n")


def _rescale_partitions(parts, total_sites):
    """Normalise partition rates so the length-weighted mean rate is 1."""
    if len(parts) < 2:
        return
    weighted = sum(rate * length for length, rate, _ in parts)
    for i, (length, rate, tree) in enumerate(parts):
        parts[i] = (length, rate * total_sites / weighted, tree)


def _branch_scale(args, part_rate, tree):
    scale = part_rate
    if args.tree_scale > 0:
        scale *= args.tree_scale / tree.total_length
    elif args.branch_scale > 0:
        scale *= args.branch_scale
    return scale


def _report_height(args, tree, scale):
    sys.stderr.write(f"  Tree height: {tree.total_length:.3f}"
                     f"  → effective: {tree.total_length * scale:.3f} subs/site\n")
    if not args.tree_scale and tree.total_length > 2.0:
        sys.stderr.write("  WARNING: tree height > 2.0 \u2014 sequences may be "
                         "saturated.\n  Consider using -d 0.5 to normalize "
                         "tree height.\n")


def _write_dataset(fv, args, run, trees, part_lens, tree_no, dataset_no):
    """Write one dataset to an already-open file handle."""
    if args.write_ancestral:
        if len(trees) > 1 and not args.separate:
            _warn("ancestral output with multiple partitions only writes first "
                  "partition's sequences; use -os for separate files per dataset")
        write_ancestral(fv, run.fmt, trees[0], run.state_chars)
    else:
        write_sequences(fv, run.fmt, trees, part_lens, trees[0].num_tips,
                        args.total_sites, run.state_chars,
                        tree_no if run.multi_tree else 0,
                        dataset_no if run.multi_dataset else 0,
                        run.is_nuc)

    if (args.write_rates and not args.quiet
            and run.rate_info.get("site_rates") is not None):
        write_rates(sys.stderr, run.rate_info["site_rates"], args.total_sites)

    if run.insert_text:
        fv.write(run.insert_text + "\n")


def _parse_args():
    if "--manual" in sys.argv:
        print(get_manual(__version__))
        sys.exit(0)

    p = argparse.ArgumentParser(
        prog="seq_sim",
        description="Monte Carlo simulation of molecular sequence evolution")
    p.add_argument("treefile", nargs="?", default=None,
                   help="Newick tree file (default: stdin)")
    p.add_argument("-m", "--model", required=True,
                   help="Substitution model: JC69, HKY, F84, GTR, JTT, WAG, "
                        "PAM, BLOSUM, LG, GENERAL")
    p.add_argument("-l", "--length", type=int, default=1000,
                   help="Sequence length (default: 1000)")
    p.add_argument("-n", "--num-datasets", type=int, default=1,
                   help="Number of datasets per tree (default: 1)")
    p.add_argument("-s", "--branch-scale", type=float, default=0.0,
                   help="Branch length scaling factor")
    p.add_argument("-d", "--tree-scale", type=float, default=0.0,
                   help="Normalize total tree height (root-to-tip) to N "
                        "subs/site. Requires rooted tree. Mutually exclusive "
                        "with -s.")
    p.add_argument("-br", "--branch-rates", action="store_true",
                   help="Treat [value] after branch lengths as per-branch "
                        "rate multipliers")
    p.add_argument("--normalize-branch-rates", action="store_true",
                   help="Scale branch rate multipliers to weighted mean = 1.0")
    p.add_argument("--alt-freqs", action="append", default=None,
                   help="Alternative composition vectors (comma-separated). "
                        "Repeat for multiple. Nuc: A,C,G,T.")
    p.add_argument("--alt-rates", action="append", default=None,
                   help="Alternative exchangeability vectors (comma-separated). "
                        "Repeat for multiple. GTR: 6 values AC,AG,AT,CG,CT,GT.")
    p.add_argument("--alt-tstv", type=float, action="append", default=None,
                   help="Alternative tstv ratios for HKY/F84. Repeat for multiple.")
    p.add_argument("--alt-freqs-file", type=str, default=None,
                   help="File with alternative composition vectors (one per line).")
    p.add_argument("--alt-rates-file", type=str, default=None,
                   help="File with alternative exchangeability vectors (one per line).")
    p.add_argument("--gfmix-cseries", type=str, default=None,
                   help="C-series profile mixture (C10-C60) for amino-acid site "
                        "heterogeneity. Mutually exclusive with --alt-freqs/"
                        "--alt-rates/--alt-tstv.")
    p.add_argument("--gfmix-weights", type=str, default=None,
                   help="Per-profile weights (C values summing to 1, comma or "
                        "space separated). Default: the C-series built-in weights.")
    p.add_argument("--gfmix-branch-hetero", type=str, default=None,
                   help="File mapping tip names to branch gamma_G and gamma_F, "
                        "one 'name gamma_G gamma_F' per line.")
    p.add_argument("--gfmix-log", action="store_true",
                   help="Write a log of per-site profile assignment, weights and "
                        "branch gammas.")
    p.add_argument("-c", "--codon-rates", type=float, nargs=3, default=None,
                   help="Codon position rates: r1 r2 r3")
    p.add_argument("-a", "--gamma", type=float, default=None,
                   help="Gamma distribution shape (alpha)")
    p.add_argument("-g", "--gamma-cats", type=int, default=None,
                   help="Number of discrete gamma categories (2-32)")
    p.add_argument("-i", "--invariable", type=float, default=None,
                   help="Proportion of invariable sites (0-1)")
    p.add_argument("-f", "--freqs", nargs="*", default=None,
                   help="State frequencies (4 for nuc, 20 for AA, or 'e' for equal)")
    p.add_argument("-t", "--tstv", type=float, default=None,
                   help="Transition/transversion ratio (HKY/F84 only)")
    p.add_argument("-r", "--rates", nargs="*", default=None,
                   help="General rate matrix values (6 for GTR, 190 for AA)")
    p.add_argument("-z", "--seed", type=int, default=None,
                   help="Random number seed")
    p.add_argument("-o", "--format", type=str, default="f",
                   help="Output format: p=PHYLIP, r=Relaxed PHYLIP, n=NEXUS, "
                        "f=FASTA. Add 's' for separate files")
    p.add_argument("-y", "--output-prefix", type=str, default=None,
                   help="Output file/directory prefix")
    p.add_argument("-u", "--suffix", type=str, default=None,
                   help="Output file suffix/extension")
    p.add_argument("-wa", "--write-ancestral", action="store_true",
                   help="Write ancestral sequences for internal nodes")
    p.add_argument("-wr", "--write-rates", action="store_true",
                   help="Write relative rate for each site to stderr")
    p.add_argument("--ancestor", type=str, default=None,
                   help="Ancestral root sequence (single string). If provided, "
                        "uses this as root instead of random generation.")
    p.add_argument("-x", "--insert-file", type=str, default=None,
                   help="Text file to insert after each dataset")
    p.add_argument("-q", "--quiet", action="store_true",
                   help="Suppress informational output")
    p.add_argument("--version", action="version", version=f"seq_sim v{__version__}")
    p.add_argument("--manual", action="store_true",
                   help="Print comprehensive usage manual and exit")
    args = p.parse_args()

    args.separate = False
    fmt = args.format.lower().replace(" ", "")
    if fmt.endswith("s"):
        args.separate = True
        fmt = fmt[:-1]
    for key, code in (("phylip", "p"), ("relaxed", "r"), ("nexus", "n"),
                      ("fasta", "f")):
        if fmt in (code, key):
            args.format = code
            break
    else:
        p.error(f"Unknown output format: {fmt}")
    if args.format == "f":
        args.separate = True

    model_name = "GTR" if args.model.upper() == "REV" else args.model.upper()
    is_aa = model_name in AA_MODELS

    args.equal_freqs = False
    if args.freqs is not None:
        tokens = _split_numbers(args.freqs)
        if len(tokens) == 1 and tokens[0].lower() in ("e", "equal"):
            args.equal_freqs = True
            args.freqs = None
        else:
            try:
                args.freqs = [float(x) for x in tokens]
            except (TypeError, ValueError):
                p.error("-f/--freqs expects 4 or 20 numeric values, "
                        "or 'e' for equal frequencies")

    if args.rates is not None:
        try:
            args.rates = [float(x) for x in _split_numbers(args.rates)]
        except (TypeError, ValueError):
            p.error("-r/--rates expects numeric values (6 for GTR, 190 for AA)")

    args.total_sites = args.length

    if args.length <= 0:
        p.error(f"--length must be > 0, got {args.length}")

    if args.gamma_cats is not None:
        if args.gamma_cats < 2 or args.gamma_cats > 32:
            p.error("Gamma categories must be between 2 and 32")
        if args.gamma is None:
            p.error("Gamma shape (-a) required with discrete categories (-g)")

    if args.invariable is not None and not 0.0 <= args.invariable < 1.0:
        p.error("Invariable proportion must be >= 0 and < 1")

    if args.codon_rates and args.gamma is not None:
        p.error("Codon rates (-c) and gamma rates (-a/-g) cannot be used together")

    if args.gamma is not None and args.gamma <= 0.0:
        p.error(f"Gamma shape (-a) must be > 0, got {args.gamma}")

    if args.codon_rates is not None and is_aa:
        p.error("-c/--codon-rates is only valid for nucleotide models")

    if args.branch_scale > 0 and args.tree_scale > 0:
        p.error("-s (branch-scale) and -d (tree-scale) cannot be used together")

    if args.codon_rates is not None:
        total = sum(args.codon_rates)
        if total <= 0:
            p.error("Codon rates must sum to a positive value")
        if abs(total - 3.0) > 1e-10:
            args.codon_rates = [r * 3.0 / total for r in args.codon_rates]

    if args.rates is not None and len(args.rates) not in (6, 190):
        p.error(f"-r/--rates expects 6 (GTR) or 190 (AA) values, "
                f"got {len(args.rates)}")
    if args.rates is not None and is_aa and len(args.rates) != 190:
        p.error(f"-r/--rates expects 190 values for amino-acid models, "
                f"got {len(args.rates)}")
    if args.freqs is not None and len(args.freqs) not in (4, 20):
        p.error(f"-f/--freqs expects 4 (nucleotide) or 20 (AA) values, "
                f"got {len(args.freqs)}")

    if args.normalize_branch_rates and not args.branch_rates:
        args.branch_rates = True

    args.alt_freqs_list = _parse_alt_vectors(args.alt_freqs, args.alt_freqs_file)
    args.alt_rates_list = _parse_alt_vectors(args.alt_rates, args.alt_rates_file)

    if args.alt_tstv and model_name not in ("HKY", "F84"):
        p.error("--alt-tstv requires HKY or F84 model")
    if args.alt_rates_list and model_name not in ("GTR",) and not is_aa:
        p.error(f"--alt-rates requires GTR or AA model, got {args.model}")
    if args.alt_rates_list:
        expected = 190 if is_aa else 6
        for vec in args.alt_rates_list:
            if len(vec) != expected:
                p.error(f"--alt-rates expects {expected} values for "
                        f"{args.model}, got {len(vec)}")

    if args.gfmix_cseries is not None:
        args.gfmix_cseries = args.gfmix_cseries.upper()
        if not is_aa:
            p.error("--gfmix-cseries requires an amino-acid model "
                    "(-m JTT/WAG/PAM/BLOSUM/LG/GENERAL)")
        if args.alt_freqs_list or args.alt_rates_list or args.alt_tstv:
            p.error("--gfmix-cseries is mutually exclusive with "
                    "--alt-freqs/--alt-rates/--alt-tstv")
        if args.gfmix_weights is not None:
            try:
                args.gfmix_weights = [float(x) for x in
                                      _split_numbers([args.gfmix_weights])]
            except ValueError:
                p.error("--gfmix-weights expects numeric values")
    else:
        if args.gfmix_weights is not None:
            p.error("--gfmix-weights requires --gfmix-cseries")
        if args.gfmix_branch_hetero is not None:
            p.error("--gfmix-branch-hetero requires --gfmix-cseries")
        if args.gfmix_log:
            p.error("--gfmix-log requires --gfmix-cseries")

    return args


def _split_numbers(values):
    """Flatten one or more "1,2 3" style arguments into tokens."""
    return [t for raw in values for t in re.split(r"[,\s]+", str(raw)) if t]


def _group_partitions(raw_trees, total_sites):
    """Group parsed trees into datasets by partition length."""
    datasets = []
    buf = []
    consumed = 0

    for length, rate, tree in raw_trees:
        if length <= 0:
            # No partition prefix: the tree is a whole dataset on its own.
            datasets.append([(total_sites, rate, tree)])
            buf = []
            consumed = 0
            continue
        buf.append((length, rate, tree))
        consumed += length
        if consumed >= total_sites:
            if consumed != total_sites:
                _warn(f"partition sum {consumed} != {total_sites}")
            datasets.append(buf)
            buf = []
            consumed = 0

    if buf:
        datasets.append(buf)
    return datasets


def _parse_alt_vectors(cli_args, file_path):
    result = []
    for spec in cli_args or []:
        result.append([float(x) for x in _split_numbers([spec])])
    if file_path:
        for line in _read_text(file_path).splitlines():
            line = line.strip()
            if line and not line.startswith("#"):
                result.append([float(x) for x in _split_numbers([line])])
    return result or None


def _exchangeability_for(model_name, rates):
    """The 190 exchangeabilities shared by every GFmix profile."""
    if model_name == "GENERAL":
        if rates is None:
            _die("--gfmix-cseries with GENERAL model requires -r/--rates "
                 "(190 values)")
        return list(rates)
    return empirical_rates(model_name)


def _parse_branch_hetero(path):
    """Parse 'name gamma_G gamma_F' lines into {name: (gamma_g, gamma_f)}."""
    result = {}
    for line in _read_text(path).splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        if len(parts) != 3:
            _die(f"--gfmix-branch-hetero line must be 'name gamma_G gamma_F', "
                 f"got: {line!r}")
        try:
            gg, gf = float(parts[1]), float(parts[2])
        except ValueError:
            _die(f"invalid gamma value in --gfmix-branch-hetero: {line!r}")
        if gg <= 0.0 or gf <= 0.0:
            _die(f"gamma values must be positive in --gfmix-branch-hetero: "
                 f"{line!r}")
        if parts[0] in result:
            _die(f"duplicate node in --gfmix-branch-hetero: {parts[0]}")
        result[parts[0]] = (gg, gf)
    return result


def _apply_branch_gammas(datasets, gamma_by_name):
    """Write each named node's gamma pair onto its node.

    Names may address tips or labelled internal nodes; the gamma applies to
    the branch that leads into the node.
    """
    matched = set()
    for parts in datasets:
        for _, _, tree in parts:
            for node in tree.node_list:
                if node.name and node.name in gamma_by_name:
                    gg, gf = gamma_by_name[node.name]
                    node.gamma_g, node.gamma_f = gg, gf
                    matched.add(node.name)
    missing = set(gamma_by_name) - matched
    if missing:
        _die(f"--gfmix-branch-hetero names not found in tree: "
             f"{sorted(missing)}")


def _write_gfmix_log_header(fv, profile_info, gamma_by_name):
    fv.write("# GFmix mixture log\n")
    fv.write(f"# C-series: {profile_info['cseries']}\n")
    fv.write("# profile weights: "
             + " ".join(f"{w:.10g}" for w in profile_info["weights"]) + "\n")
    for name in sorted(gamma_by_name):
        gg, gf = gamma_by_name[name]
        fv.write(f"# branch gamma: {name} {gg} {gf}\n")
    fv.write(f"# num_sites: {len(profile_info['site_profile'])}\n")


def _write_gfmix_log_replicate(fv, rep, site_profile):
    fv.write(f"replicate {rep}:\n")
    vals = [str(int(x)) for x in site_profile]
    for i in range(0, len(vals), 60):
        fv.write("  " + " ".join(vals[i:i + 60]) + "\n")


def _default_suffix(fmt):
    return {"p": "phy", "r": "phy", "n": "nex", "f": "fasta"}.get(fmt, "out")


def _print_model_info(args, model, rate_info, fmt, prefix):
    lines = [
        f"Model: {args.model}",
        f"  States: {model.num_states}",
        f"  Sequence length: {args.total_sites}",
        f"  Datasets per tree: {args.num_datasets}",
        f"  Output: {prefix}/ [{fmt}]",
    ]
    if rate_info["type"] == "codon":
        lines.append(f"  Codon rates: {rate_info['cat_rates']}")
    elif rate_info["type"] == "discrete_gamma":
        lines.append(f"  Gamma: shape={args.gamma}, {args.gamma_cats} categories")
    elif rate_info["type"] == "continuous_gamma":
        lines.append(f"  Gamma: shape={args.gamma} (continuous)")
    if rate_info["invariable"]:
        lines.append(f"  Invariable sites: {args.invariable}")
    if args.branch_scale:
        lines.append(f"  Branch scale: {args.branch_scale}")
    if args.tree_scale:
        lines.append(f"  Tree scale: {args.tree_scale}")
    if args.branch_rates:
        lines.append("  Branch rates: enabled (per-branch multipliers from "
                     "tree [value])")
    sys.stderr.write("\n".join(lines) + "\n\n")


